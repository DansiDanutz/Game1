/* Writes the boards and quest levels of js/levels.js and js/puzzle.js as SQL.
   node tools/gen-boards-sql.js > supabase/migrations/20261125111000_shikaku_boards.sql
   ci-check.js fails when that file no longer matches the JavaScript. */
global.window = global.window || {};
require('../js/levels.js');
require('../js/puzzle.js');

function boardsSql(){
  const bank = window.SHIKAKU_LEVELS;
  const boards = [], quest = [];
  for (const size of Object.keys(bank)) for (const tier of Object.keys(bank[size]))
    bank[size][tier].forEach((g, i) => boards.push(`  (${size}, '${tier}', ${i}, '${JSON.stringify(g)}')`));
  window.SHIKAKU_PUZZLE.WORLDS.forEach((world, w) => world.levels.forEach((l, li) => {
    // the same order levelGrid() falls back in when a bucket is empty
    const tier = [l.tier, 'expert', 'hard', 'medium', 'easy'].find((t) => (bank[l.size][t] || []).length);
    quest.push(`  (${w}, ${li}, ${l.size}, '${tier}', ${l.mult})`);
  }));
  return `-- Generated by tools/gen-boards-sql.js from js/levels.js and js/puzzle.js. Do not edit.
insert into public.shikaku_boards (size, tier, num, puzzle) values
${boards.join(',\n')}
on conflict (size, tier, num) do update set puzzle = excluded.puzzle;

insert into public.shikaku_quest (world, level, size, tier, mult) values
${quest.join(',\n')}
on conflict (world, level) do update set size = excluded.size, tier = excluded.tier, mult = excluded.mult;
`;
}
module.exports = { boardsSql };
if (require.main === module) process.stdout.write(boardsSql());
